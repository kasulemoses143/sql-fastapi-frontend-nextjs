BEGIN;
CREATE TABLE students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL CONSTRAINT student_name_not_blank CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE
);
CREATE TABLE courses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE CONSTRAINT course_code_not_blank CHECK (length(trim(code)) > 0),
    title VARCHAR(120) NOT NULL CONSTRAINT course_title_not_blank CHECK (length(trim(title)) > 0),
    credits INTEGER NOT NULL CONSTRAINT credits_range CHECK (credits BETWEEN 1 AND 6)
);
CREATE TABLE enrollments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    enrolled_on DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CONSTRAINT enrollment_status CHECK (status IN ('active', 'completed', 'withdrawn')),
    CONSTRAINT one_enrollment_per_pair UNIQUE (student_id, course_id)
);
CREATE INDEX ix_enrollments_student_id ON enrollments(student_id);
CREATE INDEX ix_enrollments_course_id ON enrollments(course_id);
COMMIT;
